describe("vectors for ports", () => {
  it("detection: every sample and the inline inputs", async () => {
    const files = samples(FIXTURES)
      .map((p) => relative(FIXTURES, p).replace(/\\/g, "/"))
      .sort()
      .map((file) => ({
        file,
        ...outcome(readFileSync(join(FIXTURES, file), "utf8")),
      }));
    const inline = INLINE.map(({ name, text }) => ({
      name,
      text,
      ...outcome(text),
    }));
    const vectors = {
      $comment:
        "Generated by packages/formats/src/vectors.test.ts from this package's behaviour: what parseReportText reads each sample as (by content, never by extension), and the inline inputs it refuses. A port must give the same format or error code.",
      files,
      inline,
    };
    await expect(JSON.stringify(vectors, null, 2) + "\n").toMatchFileSnapshot(
      join(FIXTURES, "detection-vectors.json"),
    );
    // Spot checks, so a wrong snapshot cannot hide here.
    expect(
      files.find((f) => f.file === "k6/summary-export.json"),
    ).toMatchObject({ format: "k6" });
    expect(inline.find((i) => i.name === "xml-doctype-xxe")).toMatchObject({
      error: "invalid-xml",
    });
    expect(
      inline.find((i) => i.name === "xml-doctype-inside-output-is-content"),
    ).toMatchObject({ format: "junit" });
  });

  it("schema: valid and invalid Pharos Run JSON documents", async () => {
    const cases = DOCS.map(({ name, doc }) => {
      const r = parsePharosRun(doc);
      return { name, doc, ok: r.ok, issues: r.ok ? [] : r.issues };
    });
    const vectors = {
      $comment:
        "Generated by packages/formats/src/vectors.test.ts: what parsePharosRun says of each document (ok, and the issue paths and messages). The cross-reference checks (attachment and shard refs) are not in the JSON Schema; a port checks them by hand.",
      cases,
    };
    await expect(JSON.stringify(vectors, null, 2) + "\n").toMatchFileSnapshot(
      join(FIXTURES, "schema-vectors.json"),
    );
    expect(cases.find((c) => c.name === "minimal")!.ok).toBe(true);
    expect(
      cases.find((c) => c.name === "finding-dangling-shard")!.issues[0].path,
    ).toBe("findings.0.shardRef");
  });
});
