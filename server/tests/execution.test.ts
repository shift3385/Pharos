/** Every key of `expected` is equal in `actual` (arrays element by element,
 *  same length), as the desktop's `assert_subset`. */
function expectSubset(expected: unknown, actual: unknown, path: string) {
  if (expected && typeof expected === "object" && !Array.isArray(expected)) {
    expect(actual && typeof actual === "object", path).toBe(true);
    for (const [k, v] of Object.entries(expected)) expectSubset(v, (actual as Record<string, unknown>)[k] ?? null, `${path}.${k}`);
  } else if (Array.isArray(expected)) {
    expect(Array.isArray(actual), path).toBe(true);
    expect((actual as unknown[]).length, `${path}: length`).toBe(expected.length);
    expected.forEach((x, i) => expectSubset(x, (actual as unknown[])[i], `${path}[${i}]`));
  } else {
    expect(actual, path).toEqual(expected);
  }
}

describe("shared execution vectors (the desktop checks the same file)", () => {
  const file = JSON.parse(
    readFileSync(new URL("../../src-tauri/tests/fixtures/execution-vectors.json", import.meta.url), "utf8"),
  ) as {
    cases: {
      name: string;
      kind: "summary" | "home";
      project?: ProjectData;
      filter?: ExecutionFilter;
      projects?: ProjectData[];
      request?: HomeRequest;
      expected: unknown;
    }[];
  };
  // The whole output of each vector, generated by the desktop's test.
  const golden = JSON.parse(
    readFileSync(new URL("../../src-tauri/tests/fixtures/execution-vectors.golden.json", import.meta.url), "utf8"),
  ) as Record<string, unknown>;
  it("the golden has one output per vector", () => {
    expect(Object.keys(golden).sort()).toEqual(file.cases.map((c) => c.name).sort());
  });
  for (const c of file.cases) {
    it(c.name, () => {
      const got = JSON.parse(
        JSON.stringify(c.kind === "summary" ? summarize(c.project!, c.filter!) : home(c.projects!, c.request!)),
      ) as unknown;
      expectSubset(c.expected, got, c.name);
      expect(got, `${c.name}: output differs from the golden`).toEqual(golden[c.name]);
    });
  }

  it("the order rows are read in does not matter", () => {
    for (const c of file.cases.filter((x) => x.kind === "summary")) {
      const p = c.project!;
      const reversed: ProjectData = {
        ...p,
        attempts: [...(p.attempts ?? [])].reverse(),
        defects: [...(p.defects ?? [])].reverse(),
        cases: [...(p.cases ?? [])].reverse(),
        runs: [...(p.runs ?? [])].reverse(),
      };
      expect(summarize(reversed, c.filter!), c.name).toEqual(summarize(p, c.filter!));
    }
  });

  it("orders keys, recognizes criteria and parses metrics like the desktop", () => {
    const keys = ["ATS_10", "ATS_2", "ATS_002", "ATS_1", "B", "A"].sort(naturalCmp);
    expect(keys).toEqual(["A", "ATS_1", "ATS_002", "ATS_2", "ATS_10", "B"]);
    expect(criterionKind("% de casos ejecutados")).toBe("executed");
    expect(criterionKind("Defectos críticos abiertos")).toBe("criticalDefects");
    expect(criterionKind("Tasa de éxito")).toBe("passRate");
    expect(criterionKind("Cobertura de requisitos")).toBe("coverage");
    expect(criterionKind("Sign-off by the PO")).toBeNull();
    expect(criterionKind("Casos críticos ejecutados")).toBeNull();
    expect(parseMetric("≥ 95%", "executed")).toEqual([">=", 95]);
    expect(parseMetric("95,5%", "executed")).toEqual([">=", 95.5]);
    expect(parseMetric("0", "criticalDefects")).toEqual(["=", 0]);
    expect(parseMetric("< 2", "criticalDefects")).toEqual(["<", 2]);
    expect(parseMetric("ninguno", "criticalDefects")).toBeNull();
    expect(parseMetric("1.2.3", "executed")).toBeNull();
  });
});

describe("GET /api/execution/summary", () => {
  let app: FastifyInstance;
  let pool: Pool;
  beforeAll(async () => {
    ({ app, pool } = await setupTestApp());
  });
  afterAll(async () => {
    await app.close();
    await pool.end();
  });
  beforeEach(async () => {
    await truncateAll(pool);
    await pool.query("TRUNCATE key_blocks");
  });

  const headers = (token: string) => ({
    authorization: `Bearer ${token}`,
    [VERSION_HEADER]: SERVER_VERSION,
    [FEATURES_HEADER]: SERVER_FEATURES.join(","),
  });
  async function register(email: string) {
    const res = await app.inject({
      method: "POST",
      url: "/auth/register",
      payload: { email, password: "supersecret1", displayName: "S", firstName: "A", lastName: "B" },
    });
    const token = res.json().accessToken as string;
    const call = async (method: "GET" | "POST" | "PUT", url: string, payload?: object) => {
      const r = await app.inject({ method, url, headers: headers(token), payload });
      return { status: r.statusCode, body: r.body ? r.json() : null };
    };
    return { call, userId: res.json().user.id as string };
  }
  const H = (wall: number) => `${String(wall).padStart(15, "0")}-00000-desk`;
  async function store(userId: string, entity: string, id: string, payload: Record<string, unknown>) {
    await pool.query(
      `INSERT INTO documents (user_id, entity, entity_id, payload, revision, author, deleted, hlc)
       VALUES ($1, $2, $3, $4, 1, 'u', false, $5)`,
      [userId, entity, id, payload, H(Date.now())],
    );
  }

  it("a manual and a Playwright run share the matrix; the latest final wins; editing the case changes nothing", async () => {
    const { call, userId } = await register("matrix@pharos.dev");
    const projectId = (await call("POST", "/api/projects", { name: "Checkout" })).body.id as string;
    await call("POST", "/api/requirements", { projectId, requirementKey: "REQ-001", title: "Pay" });
    const pay = (
      await call("POST", "/api/test-cases", {
        projectId,
        title: "Pay",
        status: "approved",
        priority: "high",
        data: { steps: ["open"], requirementKeys: ["REQ-001"] },
      })
    ).body;
    const key = pay.scenarioId as string;
    // A manual run (desktop, synced) fails on 1 Nov.
    await store(userId, "run", "run1", { id: "run1", projectId, runKey: "RUN-001", title: "Manual", trigger: "manual", status: "completed", startedAt: "2026-11-01T09:00:00Z", createdAt: "2026-11-01T09:00:00Z" });
    await store(userId, "result", "m1", {
      id: "m1", projectId, runId: "run1", testKey: `manual:${pay.id as string}/-/-`, testCaseId: pay.id, caseRevision: 1,
      status: "failed", attempt: 0, finishedAt: "2026-11-01T10:00:00Z", hlc: H(1),
    });
    let s = (await call("GET", `/api/execution/summary?projectId=${projectId}`)).body;
    expect(s.cases[0]).toMatchObject({ caseId: pay.id, status: "failed", last: { resultId: "m1", origin: "manual" } });

    // The Playwright report of 2 Nov passes it.
    await store(userId, "run", "run2", { id: "run2", projectId, runKey: "RUN-002", title: "CI", trigger: "import", sourceTool: "playwright", status: "completed", startedAt: "2026-11-02T09:00:00Z", createdAt: "2026-11-02T09:00:00Z", build: "1.4.2" });
    await store(userId, "run_shard", "s1", { id: "s1", projectId, runId: "run2", sourceFileSha256: "abc", normalizerVersion: 1, importedAt: "2026-11-02T09:05:00Z" });
    await store(userId, "result", "i1", {
      id: "i1", projectId, runId: "run2", shardId: "s1", testKey: "pay.spec.ts::pays", configurationLabel: "chromium",
      status: "passed", attempt: 0, finishedAt: "2026-11-02T09:00:01Z", attributes: { tags: [`@${key}`], name: "pays" }, hlc: H(2),
    });
    s = (await call("GET", `/api/execution/summary?projectId=${projectId}`)).body;
    expect(s.contractVersion).toBe(1);
    expect(s.runs.map((r: { id: string }) => r.id)).toEqual(["run2", "run1"]);
    expect(s.cases[0]).toMatchObject({ status: "passed", last: { resultId: "i1", runKey: "RUN-002", origin: "imported", sourceTool: "playwright" } });
    expect(s.requirements[0]).toMatchObject({ requirementKey: "REQ-001", status: "passed", covered: true });
    expect(s.options.builds).toEqual(["1.4.2"]);
    // Filtered to the manual run's build (none): only the CI build has runs.
    const ci = (await call("GET", `/api/execution/summary?projectId=${projectId}&build=1.4.2`)).body;
    expect(ci.runs).toHaveLength(1);

    // A newer manual attempt on 3 Nov, against the case's current revision.
    const rev = await pool.query<{ id: string }>(
      `SELECT entity_id AS id FROM documents WHERE user_id = $1 AND entity = 'test_case_revision'
          AND payload->>'testCaseId' = $2 ORDER BY seq DESC LIMIT 1`,
      [userId, pay.id],
    );
    await store(userId, "run", "run3", { id: "run3", projectId, runKey: "RUN-003", title: "Retest", trigger: "manual", status: "completed", startedAt: "2026-11-03T08:00:00Z", createdAt: "2026-11-03T08:00:00Z" });
    await store(userId, "result", "m2", {
      id: "m2", projectId, runId: "run3", testKey: `manual:${pay.id as string}/-/-`, testCaseId: pay.id,
      testCaseRevisionId: rev.rows[0].id, status: "blocked", attempt: 0, finishedAt: "2026-11-03T09:00:00Z", hlc: H(3),
    });
    const summary = async (q = "") => (await call("GET", `/api/execution/summary?projectId=${projectId}${q}`)).body;
    const before = (await summary()).cases[0];
    expect(before).toMatchObject({ status: "blocked", last: { resultId: "m2", stale: false } });
    const ciBefore = await summary("&build=1.4.2");
    expect(ciBefore.cases[0].last).toMatchObject({ resultId: "i1", status: "passed" });

    // A status-only edit changes nothing executable: nothing is outdated.
    const statusOnly = await call("PUT", `/api/test-cases/${pay.id as string}`, {
      input: { projectId, title: "Pay", status: "draft", priority: "low", data: { steps: ["open"], requirementKeys: ["REQ-001"] } },
      revision: pay.revision,
    });
    expect(statusOnly.status).toBe(200);
    expect((await summary()).cases[0].last).toMatchObject({ resultId: "m2", stale: false });

    // Editing the steps changes none of the results; they become outdated.
    const put = await call("PUT", `/api/test-cases/${pay.id as string}`, {
      input: { projectId, title: "Pay by card", status: "approved", priority: "high", data: { steps: ["open", "pay"], requirementKeys: ["REQ-001"] } },
      revision: statusOnly.body.revision,
    });
    expect(put.status).toBe(200);
    const after = (await summary()).cases[0];
    expect(after.status).toBe(before.status);
    expect(after.last).toEqual({ ...before.last, stale: true });
    // The Playwright result, alone under the CI build: unchanged.
    const ciAfter = await summary("&build=1.4.2");
    for (const k of ["resultId", "revisionId", "status"]) expect(ciAfter.cases[0].last[k]).toEqual(ciBefore.cases[0].last[k]);
    expect(ciAfter.cases[0].flowId).toEqual(ciBefore.cases[0].flowId);
    // Everything else of each target stays; only «outdated» follows the edit.
    type T = { last: Record<string, unknown> };
    const unstale = (ts: T[]) => ts.map((t) => ({ ...t, last: { ...t.last, stale: null } }));
    expect(unstale(ciAfter.targets as T[])).toEqual(unstale(ciBefore.targets as T[]));
    expect(ciAfter.cases[0].last.stale).toBe(ciAfter.cases[0].last.revisionId !== null);
  });

  it("a deleted run (a synced tombstone, EJE-07) counts nowhere; a defect linked to its result still reaches the case", async () => {
    const { call, userId } = await register("deleted@pharos.dev");
    const projectId = (await call("POST", "/api/projects", { name: "Del" })).body.id as string;
    const pay = (await call("POST", "/api/test-cases", { projectId, title: "Pay", data: { steps: ["open"] } })).body;
    const run = (id: string, key: string) => ({ id, projectId, runKey: key, title: key, trigger: "manual", status: "completed", createdAt: "2026-11-01T09:00:00Z" });
    const result = (id: string, runId: string, status: string, finishedAt: string) => ({
      id, projectId, runId, testKey: `manual:${pay.id as string}/-/-`, testCaseId: pay.id, status, attempt: 0, finishedAt, hlc: H(1),
    });
    await store(userId, "run", "kept", run("kept", "RUN-001"));
    await store(userId, "run", "gone", run("gone", "RUN-002"));
    await store(userId, "result", "ok", result("ok", "kept", "passed", "2026-11-01T10:00:00Z"));
    await store(userId, "result", "ko", result("ko", "gone", "failed", "2026-11-02T10:00:00Z"));
    await store(userId, "defect", "d1", { id: "d1", projectId, defectKey: "DEF-001", title: "Bug", severity: "major", status: "open" });
    await store(userId, "defect_link", "l1", { id: "l1", projectId, defectId: "d1", targetKind: "result", targetId: "ko" });
    const summary = async () => (await call("GET", `/api/execution/summary?projectId=${projectId}`)).body;
    expect((await summary()).cases[0].status).toBe("failed");

    await pool.query("UPDATE documents SET deleted = true WHERE user_id = $1 AND entity = 'run' AND entity_id = 'gone'", [userId]);

    const s = await summary();
    expect(s.cases[0]).toMatchObject({ status: "passed", last: { resultId: "ok" }, defectIds: ["d1"] });
    expect(s.runs.map((r: { id: string }) => r.id)).toEqual(["kept"]);
    expect(s.progress).toMatchObject({ failed: 0, passed: 1 });
    expect(s.defects.total).toBe(1);
  });

  it("reads each kind once, however many projects (no N+1), without the write lock", async () => {
    const { call, userId } = await register("bulk@pharos.dev");
    const counted = createDomainStore(pool, createServerClock());
    let calls = 0;
    const reading: typeof counted = {
      ...counted,
      read: (u, fn) =>
        counted.read(u, (r) =>
          fn({
            list: (...a) => (calls++, r.list(...a)),
            projects: (...a) => (calls++, r.projects(...a)),
          }),
        ),
      tx: () => {
        throw new Error("the derivation must not take the write lock");
      },
    };
    const service = createExecutionService(reading);
    const ids: string[] = [];
    const costOf = async (projectIds: string[]) => {
      calls = 0;
      await service.homeMetrics(userId, { projectIds, dayStarts: [0], now: Date.now(), windows: [] });
      return calls;
    };
    for (const name of ["A", "B", "C"]) {
      const id = (await call("POST", "/api/projects", { name })).body.id as string;
      await call("POST", "/api/test-cases", { projectId: id, title: `Case ${name}`, data: { steps: ["x"] } });
      ids.push(id);
    }
    const one = await costOf([ids[0]]);
    expect(await costOf(ids)).toBe(one);
    calls = 0;
    expect((await service.summary(userId, { projectId: ids[1] }))?.cases).toHaveLength(1);
    expect(calls).toBe(one);
    // A project asked for twice is read and counted once.
    const twice = await service.homeMetrics(userId, { projectIds: [ids[0], ids[0]], dayStarts: [0], now: Date.now(), windows: [] });
    expect(twice.projects).toHaveLength(1);
  });

  it("the web sets a requirement's risk; a missing key keeps it, null clears it (TRZ-04)", async () => {
    const { call } = await register("risk@pharos.dev");
    const projectId = (await call("POST", "/api/projects", { name: "Risk" })).body.id as string;
    const r = (await call("POST", "/api/requirements", { projectId, title: "Pay", riskLikelihood: 4, riskImpact: 5 })).body;
    expect(r).toMatchObject({ riskLikelihood: 4, riskImpact: 5 });
    const level = async () => (await call("GET", `/api/execution/summary?projectId=${projectId}`)).body.requirements[0];
    expect(await level()).toMatchObject({ riskLevel: 20, riskBand: "high" });
    const kept = await call("PUT", `/api/requirements/${r.id as string}`, { input: { projectId, title: "Pay v2" }, revision: r.revision });
    expect(kept.body).toMatchObject({ title: "Pay v2", riskLikelihood: 4, riskImpact: 5 });
    const cleared = await call("PUT", `/api/requirements/${r.id as string}`, {
      input: { projectId, title: "Pay v2", riskLikelihood: null, riskImpact: 2 },
      revision: kept.body.revision,
    });
    expect(cleared.body).toMatchObject({ riskLikelihood: null, riskImpact: 2 });
    expect(await level()).toMatchObject({ riskLevel: null, riskBand: "unassessed" });
    expect((await call("POST", "/api/requirements", { projectId, title: "Bad", riskLikelihood: 6 })).status).toBe(400);
  });

  it("dayStarts, periods and other users", async () => {
    const { call } = await register("daily@pharos.dev");
    const projectId = (await call("POST", "/api/projects", { name: "Daily" })).body.id as string;
    const ok = await call("GET", `/api/execution/summary?projectId=${projectId}&dayStarts=1792792800000,1792879200000&from=1&to=2`);
    expect(ok.status).toBe(200);
    expect(ok.body.daily.map((d: { dayStart: number }) => d.dayStart)).toEqual([1792792800000, 1792879200000]);
    expect(ok.body.filter).toMatchObject({ from: 1, to: 2 });
    expect((await call("GET", `/api/execution/summary?projectId=${projectId}&dayStarts=a,b`)).status).toBe(400);
    // Strictly ascending, as the desktop asks.
    expect((await call("GET", `/api/execution/summary?projectId=${projectId}&dayStarts=2,1`)).status).toBe(400);
    expect((await call("GET", `/api/execution/summary?projectId=${projectId}&dayStarts=1,1`)).status).toBe(400);
    const other = await register("other@pharos.dev");
    expect((await other.call("GET", `/api/execution/summary?projectId=${projectId}`)).body).toBeNull();
  });
});
