// Execution metrics of the Home (RED-W6). The numbers come from ONE call
// (`home_metrics` on the desktop, `GET /api/home/metrics` on the web), which
// only runs the shared execution derivation of step 10 (EJE-03/04, contract
// v1 §2.4). This file holds the contract types, the request the client
// builds (its local days, so neither Rust nor the server deal with time
// zones) and pure mappers from the payload to what each widget draws. It
// derives nothing: no latest final, no pass rate, no criteria evaluation.

import type {
  DailyCount,
  ExecutionProgress,
  ExitCriterion,
  HomeMetrics,
  HomeProject as ProjectMetrics,
  HomeRequest as HomeMetricsRequest,
  QueueRef,
  WindowCounts,
} from "@shared/contracts/contract";
import { isoDay, periodDays, PERIODS, type HomeProject, type Period } from "./homeData";

// ---- contract v1 (generated by ts-rs from the step-10 derivation) ----------

export type { DailyCount, ExitCriterion, HomeMetrics, HomeMetricsRequest, ProjectMetrics, QueueRef };
/** `executed = total − notRun` (re-test counts as executed). */
export type ProgressSummary = ExecutionProgress;
export type StatusCounts = Omit<ExecutionProgress, "total" | "executed">;
/** Latest final per target among the attempts of a window (activity). */
export type WindowRollup = WindowCounts;
export type QueueTab = "notRun" | "blocked" | "retest";

// ---- request -------------------------------------------------------------------

/** Days the request covers: the longest period (30 days, or this month when
 *  it is longer), so switching period never refetches. */
export function requestDays(today: Date): Date[] {
  return periodDays(today.getDate() > 30 ? "month" : "30d", today);
}

export function metricsRequest(now: Date): HomeMetricsRequest {
  const days = requestDays(now);
  return {
    dayStarts: days.map((d) => d.getTime()),
    now: now.getTime(),
    windows: PERIODS.map((id) => ({
      id,
      fromIndex: days.length - periodDays(id, now).length,
    })),
  };
}

/** Cache key of a request: the user and the local day it was built on. */
export const metricsKey = (ownerId: string, now: Date) => `${ownerId}|${isoDay(now)}`;

// ---- mappers (presentation only) -------------------------------------------------

export function byProject(m: HomeMetrics | null): Map<string, ProjectMetrics> {
  return new Map((m?.projects ?? []).map((p) => [p.projectId, p]));
}

/** A day of the chart: «Otras» = blocked + skipped + unknown statuses. */
export interface DailyPoint {
  day: Date;
  passed: number;
  failed: number;
  others: number;
  manual: number;
  imported: number;
  total: number;
}

/** The buckets of a period, aligned with its days (empty without data). */
export function dailySeries(m: HomeMetrics | null, period: Period, today: Date): DailyPoint[] {
  const days = periodDays(period, today);
  const all = m?.daily ?? [];
  const offset = all.length - days.length;
  return days.map((day, i) => {
    const b = all[offset + i];
    return b
      ? {
          day,
          passed: b.passed,
          failed: b.failed,
          others: b.blocked + b.skipped + b.other,
          manual: b.manual,
          imported: b.imported,
          total: b.total,
        }
      : { day, passed: 0, failed: 0, others: 0, manual: 0, imported: 0, total: 0 };
  });
}

/** A round axis maximum (1, 2, 5 × 10ⁿ) at or above the highest day. */
export function axisMax(points: { total: number }[]): number {
  const top = Math.max(0, ...points.map((p) => p.total));
  if (top === 0) return 0;
  const base = 10 ** Math.floor(Math.log10(top));
  return [1, 2, 5, 10].map((k) => k * base).find((v) => v >= top)!;
}

export interface ExecRow {
  /** Null until the metrics load (unknown, never zero). */
  counts: ProgressSummary | null;
  /** executed / total, 0..1; null without cases or metrics. */
  executedShare: number | null;
  lastExecutedAt: string | null;
}

export function execRow(m: ProjectMetrics | undefined): ExecRow {
  const counts = m?.counts ?? null;
  return {
    counts,
    executedShare: counts?.total ? counts.executed / counts.total : null,
    lastExecutedAt: m?.lastExecutedAt ?? null,
  };
}

export interface ExecutionKpis {
  pending: number;
  blocked: number;
  total: number;
  openDefects: number;
  criticalDefects: number;
  /** Of the chosen period. */
  rate: WindowRollup | null;
}

/** The KPIs that come from executions, summed over the open projects. Only
 *  meaningful with metrics: the cards show «—» / «…» until then. */
export function executionKpis(
  projects: HomeProject[],
  m: HomeMetrics | null,
  period: Period,
): ExecutionKpis {
  const pm = byProject(m);
  const out = { pending: 0, blocked: 0, total: 0, openDefects: 0, criticalDefects: 0 };
  for (const p of projects) {
    const x = pm.get(p.id);
    if (!x) continue;
    out.pending += x.counts.notRun + x.counts.blocked;
    out.blocked += x.counts.blocked;
    out.total += x.counts.total;
    out.openDefects += x.defects.open;
    out.criticalDefects += x.defects.openBySeverity.critical;
  }
  return { ...out, rate: m?.windows[period] ?? null };
}

export type ExitStatus = "met" | "risk" | "unknown";

/** A project's exit status for the picker filters: «En riesgo» when any
 *  evaluable criterion is not met, «Cumplen» when every evaluable one is met
 *  (and there is one), else unknown. */
export function exitStatus(m: ProjectMetrics | undefined): ExitStatus {
  const known = (m?.exitCriteria ?? []).filter((c) => c.met !== null);
  if (known.some((c) => c.met === false)) return "risk";
  return known.length ? "met" : "unknown";
}

export interface QueueRow extends QueueRef {
  projectId: string;
  projectName: string;
}

const PRIORITY_RANK: Record<string, number> = { critical: 0, high: 1, medium: 2, low: 3 };
const rank = (priority: string) => PRIORITY_RANK[priority] ?? 4;

/** Milliseconds of a stored time (RFC 3339, or SQLite's zone-less
 *  `YYYY-MM-DD HH:MM:SS`, which is UTC); null when absent or unparsable. */
export function instantOf(s: string | null): number | null {
  if (!s) return null;
  const t = s.trim().replace(" ", "T");
  const ms = Date.parse(/(?:Z|[+-]\d{2}:?\d{2})$/i.test(t) ? t : `${t}Z`);
  return Number.isNaN(ms) ? null : ms;
}

/** A tab of «Próximas pruebas» over every project. The derivation gives one
 *  ref per case (its R5 status), the first `queueLimit` of each project in
 *  its order, and the full count of cases per tab, so the badge and the rows
 *  count the same thing: cases. Merging the projects keeps the derivation's
 *  order: priority, then the newest last execution (compared as instants;
 *  none last), then the case id in natural order. A case seen twice in a
 *  project is kept once, before the limit. */
export function queueRows(
  projects: HomeProject[],
  m: HomeMetrics,
  tab: QueueTab,
  limit = 5,
): QueueRow[] {
  const pm = byProject(m);
  const rows: (QueueRow & { at: number | null })[] = [];
  for (const p of projects) {
    const seen = new Set<string>();
    for (const ref of pm.get(p.id)?.queue[tab] ?? []) {
      if (seen.has(ref.caseId)) continue;
      seen.add(ref.caseId);
      rows.push({ ...ref, projectId: p.id, projectName: p.name, at: instantOf(ref.lastAt) });
    }
  }
  rows.sort(
    (a, b) =>
      rank(a.priority) - rank(b.priority) ||
      (a.at === null ? 1 : 0) - (b.at === null ? 1 : 0) ||
      (b.at ?? 0) - (a.at ?? 0) ||
      a.scenarioId.localeCompare(b.scenarioId, undefined, { numeric: true }),
  );
  return rows.slice(0, limit).map(({ at: _at, ...row }) => row);
}

export function queueCounts(m: HomeMetrics | null): Record<QueueTab, number> | null {
  if (!m) return null;
  const out = { notRun: 0, blocked: 0, retest: 0 };
  for (const p of m.projects)
    for (const k of Object.keys(out) as QueueTab[]) out[k] += p.queue.counts[k];
  return out;
}
